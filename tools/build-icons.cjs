#!/usr/bin/env node
/*
 * 25-11-2026, faster loading: writes resources/scss/_icons.scss with only the Bootstrap Icons the app
 * uses, in place of the full 2,000-icon stylesheet (about 80 KB of CSS).
 *
 * An icon is kept when its name appears anywhere in the sources, as `bi-name` or as a quoted 'name'
 * (icon names kept in PHP / JS arrays and joined as `bi-${icon}`), plus the `-fill` twin of every
 * kept icon (Blade `bi-house{{ $active ? '-fill' : '' }}`). It errs on the side of keeping more.
 * Runs before every `npm run build` / `npm run dev`; tests/Feature/IconSubsetTest.php checks it.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const map = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/bootstrap-icons/font/bootstrap-icons.json'), 'utf8'));
const dirs = ['resources/views', 'resources/js', 'app', 'config', 'database', 'routes'];
const exts = /\.(php|js|cjs|mjs|scss|json)$/;

const found = new Set();
const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, e.name);
        if (e.isDirectory()) { walk(p); continue; }
        if (!exts.test(e.name)) continue;
        const text = fs.readFileSync(p, 'utf8');
        for (const m of text.matchAll(/bi-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) found.add(m[1]);
        // quoted words: 'check-circle-fill text-success' gives check-circle-fill and text-success
        for (const m of text.matchAll(/['"`]([^'"`\n]{1,80})['"`]/g)) m[1].split(/[\s,]+/).forEach((w) => /^[a-z0-9]+(-[a-z0-9]+)*$/.test(w) && found.add(w));
        // a prefix joined with a value on the same line: bi-file-earmark-${x ? 'pdf' : 'image'}
        for (const line of text.split('\n')) {
            for (const m of line.matchAll(/bi-([a-z0-9-]+)-(?:\$\{|\{\{)/g)) {
                for (const q of line.matchAll(/['"`]([^'"`]{1,80})['"`]/g)) q[1].split(/[\s,]+/).forEach((w) => found.add(`${m[1]}-${w}`));
            }
        }
    }
};
dirs.forEach((d) => fs.existsSync(path.join(root, d)) && walk(path.join(root, d)));

const keep = new Set();
for (const name of found) {
    // a longer match such as "bi-check2-circle-fill-text" also names its shorter icons
    const parts = name.split('-');
    for (let i = parts.length; i > 0; i--) {
        const n = parts.slice(0, i).join('-');
        if (map[n] !== undefined) { keep.add(n); break; }
    }
}
for (const n of [...keep]) if (map[`${n}-fill`] !== undefined) keep.add(`${n}-fill`);

const names = [...keep].sort();
const hex = (n) => map[n].toString(16);
const out = `// GENERATED by tools/build-icons.cjs (npm run build). Do not edit; ${names.length} of ${Object.keys(map).length} Bootstrap Icons.
@font-face {
  font-display: block;
  font-family: "bootstrap-icons";
  src: url("../../node_modules/bootstrap-icons/font/fonts/bootstrap-icons.woff2") format("woff2");
}
.bi::before, [class^="bi-"]::before, [class*=" bi-"]::before {
  display: inline-block; font-family: bootstrap-icons !important; font-style: normal; font-weight: normal !important; font-variant: normal;
  text-transform: none; line-height: 1; vertical-align: -.125em; -webkit-font-smoothing: antialiased; -moz-osx-font-smoothing: grayscale;
}
${names.map((n) => `.bi-${n}::before { content: "\${hex(n)}"; }`).join('\n')}
`;
fs.writeFileSync(path.join(root, 'resources/scss/_icons.scss'), out);
console.log(`icons: ${names.length} of ${Object.keys(map).length} kept -> resources/scss/_icons.scss`);
